import { Check, Copy, ExternalLink } from "lucide-react";
import { useState } from "react";
import { API_BASE, DOCS_URL } from "../api";
import { Card, PageHeader, Segmented } from "../components/ui";

const ENDPOINTS: Array<[string, string, string]> = [
  ["POST", "/predict", "Score one transaction → decision, 0–100 risk score, reason codes. ?model=v2 to pin a version."],
  ["POST", "/predict/compare", "Score with every registered version side by side."],
  ["POST", "/predict/batch", "Score up to 5,000 JSON transactions; evaluates against Class if present."],
  ["POST", "/predict/upload", "Score a CSV / XLSX file (≤ 20,000 rows)."],
  ["GET", "/models", "Registry index: champion, versions, headline metrics."],
  ["GET", "/models/{version}", "Full model card: curves, thresholds, importance, lineage."],
  ["GET", "/schema", "Input features with training statistics."],
  ["GET", "/samples", "Held-out test transactions for demos."],
  ["POST", "/monitor/drift", "PSI drift report for a window of transactions."],
  ["GET", "/monitor/drift/simulate", "Drift report for a simulated scenario."],
  ["GET", "/metrics", "Service counters and latency percentiles."],
  ["GET", "/health", "Liveness, loaded versions and champion."],
];

const BODY = `{
  "transaction_id": "TX-100042",
  "Time": 7310, "Amount": 129.99,
  "V1": -1.36, "V2": -0.07, "V3": 2.54, "V4": 2.1,
  "...": "V5 – V28",
  "V12": -1.9, "V14": -3.6, "V17": -2.8
}`;

const RESPONSE = `{
  "transaction_id": "TX-100042",
  "model_version": "v3",
  "fraud_probability": 0.9946,
  "risk_score": 99.9,
  "risk_level": "critical",
  "decision": "block",
  "thresholds": { "review": 0.0087, "block": 0.3352 },
  "reasons": [
    { "feature": "V14", "value": -4.44, "baseline": 0.30,
      "contribution": 6.45, "direction": "increases_risk" },
    { "feature": "Amount", "value": 728.7, "baseline": 26.63,
      "contribution": 3.74, "direction": "increases_risk" }
  ],
  "latency_ms": 61.2
}`;

export function Developers() {
  const [lang, setLang] = useState<"curl" | "python" | "js">("curl");
  const [copied, setCopied] = useState(false);
  const snippets = {
    curl: `curl -X POST "${API_BASE}/predict?model=v3" \\
  -H "Content-Type: application/json" \\
  -d @transaction.json`,
    python: `import requests

tx = {...}  # Time, V1..V28, Amount
r = requests.post("${API_BASE}/predict", json=tx, timeout=10)
r.raise_for_status()
result = r.json()
print(result["decision"], result["risk_score"], result["reasons"][0]["feature"])`,
    js: `const res = await fetch("${API_BASE}/predict", {
  method: "POST",
  headers: { "Content-Type": "application/json" },
  body: JSON.stringify(transaction),
});
const { decision, risk_score, reasons } = await res.json();`,
  };
  const copy = async () => {
    await navigator.clipboard.writeText(snippets[lang]).catch(() => undefined);
    setCopied(true);
    window.setTimeout(() => setCopied(false), 1500);
  };

  return (
    <div className="page">
      <PageHeader
        eyebrow="Build"
        title="API & Docs"
        description={<>Everything in this console is a call to the public REST API at <code>{API_BASE}</code>. Interactive OpenAPI docs are generated by FastAPI.</>}
        actions={<a className="btn btn-primary" href={DOCS_URL} target="_blank" rel="noreferrer"><ExternalLink size={15} /><span>Open Swagger UI</span></a>}
      />

      <div className="grid grid-2">
        <Card title="Quickstart" actions={
          <>
            <Segmented label="Language" value={lang} onChange={setLang} options={[
              { value: "curl", label: "cURL" }, { value: "python", label: "Python" }, { value: "js", label: "JavaScript" },
            ]} />
            <button type="button" className="icon-btn" onClick={copy} aria-label="Copy snippet">{copied ? <Check size={15} /> : <Copy size={15} />}</button>
          </>
        }>
          <pre className="code">{snippets[lang]}</pre>
          <h3 className="sub-head">Request body</h3>
          <pre className="code">{BODY}</pre>
        </Card>
        <Card title="Response">
          <pre className="code">{RESPONSE}</pre>
          <ul className="notes">
            <li><strong>risk_score</strong> is monotone in probability and anchored so 50 = review and 80 = block for every version.</li>
            <li><strong>contribution</strong> is the change in fraud log-odds when the input is replaced by its training median.</li>
            <li>Every response carries <code>X-Request-ID</code> and <code>X-Process-Time-Ms</code> headers.</li>
          </ul>
        </Card>
      </div>

      <Card title="Endpoints" subtitle={`Base URL ${API_BASE}`} pad={false}>
        <table className="table">
          <thead><tr><th>Method</th><th>Path</th><th>Description</th></tr></thead>
          <tbody>
            {ENDPOINTS.map(([method, path, text]) => (
              <tr key={path + method}>
                <td><span className={`method method-${method.toLowerCase()}`}>{method}</span></td>
                <td className="mono">{path}</td>
                <td className="small">{text}</td>
              </tr>
            ))}
          </tbody>
        </table>
      </Card>
    </div>
  );
}
